"""**KNN Regression Class**"""

class KNNRegression:
    def __init__(self, k=5):
        self.k = k
    def fit(self, X_train, y_train):
        self.X_train = X_train
        self.y_train = y_train
    def euclidean_distance(self, x1, x2):
        distance = np.sqrt(np.sum((x1 - x2) ** 2))
        return distance
    def get_neighbors(self, test_point):
        distances = []
        for i in range(len(self.X_train)):
            distance = self.euclidean_distance(test_point, self.X_train[i])
            distances.append((distance, self.y_train[i]))
        distances.sort(key=lambda x: x[0])
        neighbors = distances[:self.k]
        return neighbors
    def predict_one(self, test_point):
        neighbors = self.get_neighbors(test_point)
        total = 0
        for distance, price in neighbors:
            total += price
        prediction = total / len(neighbors)
        return prediction
    def predict(self, X_test):
        predictions = []
        for test_point in X_test:
            prediction = self.predict_one(test_point)
            predictions.append(prediction)
        return np.array(predictions)

